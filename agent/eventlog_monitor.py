class EventLogMonitor:
    def __init__(self):
        self.hostname = get_hostname()

    def read_event_logs(self, max_records=20):
        logs = []
        if platform.system() == "Windows":
            try:
                import win32evtlog
                server = 'localhost'
                log_types = ['Security', 'System', 'Application']
                
                for log_type in log_types:
                    try:
                        hand = win32evtlog.OpenEventLog(server, log_type)
                        flags = win32evtlog.EVENTLOG_BACKWARDS_READ | win32evtlog.EVENTLOG_SEQUENTIAL_READ
                        events = win32evtlog.ReadEventLog(hand, flags, 0)
                        
                        count = 0
                        for event in events:
                            if count >= max_records:
                                break
                            event_id = event.EventID & 0xFFFF
                            source = event.SourceName
                            time_generated = event.TimeGenerated.isoformat() if event.TimeGenerated else datetime.now().isoformat()
                            
                            severity, description, mitre = EVENT_ID_SEVERITY_MAP.get(
                                event_id, ("INFO", f"Event ID {event_id}", "N/A")
                            )

                            logs.append({
                                "log_channel": log_type,
                                "event_id": event_id,
                                "source": source,
                                "message": f"{description} - Generated by {source}",
                                "computer": self.hostname,
                                "user": str(event.StringInserts[0]) if event.StringInserts else "SYSTEM",
                                "severity": severity,
                                "mitre_technique": mitre,
                                "timestamp": time_generated
                            })
                            count += 1
                        win32evtlog.CloseEventLog(hand)
                    except Exception as e:
                        logger.debug(f"Failed to read {log_type} log channel: {e}")
                if logs:
                    return logs
            except Exception as e:
                logger.debug(f"win32evtlog error, using mock event logs: {e}")

        return self._generate_fallback_logs()

